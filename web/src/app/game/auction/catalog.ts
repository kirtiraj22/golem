export function silhouettesForCategories(
  categories: ItemCategory[]
): LotSilhouette[] {
  const unique = Array.from(new Set(categories));

  return unique.map((category) => ({
    category,
    label: CATEGORY_LABELS[category],
    icon: CATEGORY_ICONS[category],
  }));
}
